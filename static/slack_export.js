// Slack / Teams Summary Exporter

window.SlackExporter = {
  copyToClipboard: async function(dossier) {
    if (!dossier) return alert("No active dossier available to copy.");

    const rootCause = dossier.ranked ? dossier.ranked.find(r => r.verdict === "ROOT_CAUSE") : null;
    const causeName = rootCause ? rootCause.name : "Under Investigation";
    const confidence = rootCause ? (rootCause.confidence * 100).toFixed(1) : "0";

    const summaryText = `
🚨 *[CLARION INCIDENT REPORT]*
• *Dossier ID:* \`${dossier.dossier_id || 'N/A'}\`
• *Primary Root Cause:* *${causeName}* (${confidence}% Confidence)
• *Anomaly Impact:* -${dossier.anomaly?.drop_pct || 0}% Completion Drop
• *Onset Time:* ${dossier.anomaly?.onset || 'N/A'}

🔍 *Naïve Alert Suppressed:*
• Symptom: ~${dossier.naive_alert?.label || 'N/A'}~ (Verified Red Herring)

🛠️ *Recommended Action:*
• ${dossier.remediation?.[0]?.action || 'Inspect system logs'}

_Generated by Clarion Deterministic Causal Reasoning Engine_
`.trim();

    try {
      await navigator.clipboard.writeText(summaryText);
      alert("Incident summary copied to clipboard in Slack format!");
    } catch (err) {
      console.error("Failed to copy summary:", err);
      alert("Failed to copy automatically. Please copy manually.");
    }
  }
};